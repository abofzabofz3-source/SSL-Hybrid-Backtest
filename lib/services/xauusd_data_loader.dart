  static List<Candle> _parseCandleData(List<Map<String, dynamic>> data) {
    return data.map((item) {
      try {
        DateTime date = DateTime.parse(item['date']);
        return Candle(
          timestamp: date,
          open: (item['o'] as num).toDouble(),
          high: (item['h'] as num).toDouble(),
          low: (item['l'] as num).toDouble(),
          close: (item['c'] as num).toDouble(),
          volume: (item['v'] as num).toInt(),
        );
      } catch (e) {
        print('Error parsing candle data: $e');
        return Candle(
          timestamp: DateTime.now(),
          open: 0,
          high: 0,
          low: 0,
          close: 0,
          volume: 0,
        );
      }
    }).toList();
